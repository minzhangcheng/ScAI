import { createPortal } from 'react-dom'
import { AlertTriangle, FlaskConical } from 'lucide-react'
import { useAppStore } from '../stores/appStore'

const DISCLAIMER_KEY = 'intesc_disclaimer_accepted'

export function hasAcceptedDisclaimer(): boolean {
  return localStorage.getItem(DISCLAIMER_KEY) === '1'
}

interface DisclaimerDialogProps {
  onAccept: () => void
}

export function DisclaimerDialog({ onAccept }: DisclaimerDialogProps) {
  const { language } = useAppStore()
  const zh = language === 'zh'

  const handleAccept = () => {
    localStorage.setItem(DISCLAIMER_KEY, '1')
    onAccept()
  }

  return createPortal(
    <div className="fixed inset-0 z-[100] flex items-center justify-center bg-black/60 backdrop-blur-sm">
      <div className="bg-white rounded-2xl shadow-2xl w-full max-w-lg mx-4 overflow-hidden">
        {/* Header */}
        <div className="bg-gradient-to-r from-violet-600 to-indigo-600 px-6 py-5">
          <div className="flex items-center gap-3">
            <FlaskConical className="w-7 h-7 text-white shrink-0" />
            <div>
              <h1 className="text-lg font-bold text-white">InteSc</h1>
              <p className="text-sm text-violet-200">
                {zh
                  ? 'AI 驱动的单细胞测序整合分析平台'
                  : 'AI-Powered Integrated Single-Cell Sequencing Analysis'}
              </p>
            </div>
          </div>
        </div>

        {/* Body */}
        <div className="px-6 py-5 space-y-4">
          <p className="text-slate-700 leading-relaxed">
            {zh
              ? 'InteSc 是一个由人工智能驱动的单细胞测序数据分析平台，集成了多种 AI 智能体，能够自动完成数据处理、分析、可视化与报告生成等任务。'
              : 'InteSc is an AI-driven single-cell sequencing analysis platform that integrates multiple AI agents to automate data processing, analysis, visualization, and report generation.'}
          </p>

          <div className="flex gap-3 bg-amber-50 border border-amber-200 rounded-xl p-4">
            <AlertTriangle className="w-5 h-5 text-amber-500 shrink-0 mt-0.5" />
            <div className="space-y-1">
              <p className="font-semibold text-amber-800">
                {zh ? '重要提示' : 'Important Notice'}
              </p>
              <p className="text-sm text-amber-700 leading-relaxed">
                {zh
                  ? 'AI 可能会产生错误或不准确的结果。请务必对系统输出的分析结果、图表及结论进行独立核实，不可将其作为唯一依据。'
                  : 'AI may produce errors or inaccurate results. Please independently verify all analysis outputs, figures, and conclusions generated by the system, and do not rely solely on them.'}
              </p>
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="px-6 pb-6">
          <button
            onClick={handleAccept}
            className="w-full py-3 bg-violet-600 hover:bg-violet-700 text-white font-semibold rounded-xl transition-colors"
          >
            {zh ? '我已了解，进入系统' : 'I Understand, Enter System'}
          </button>
        </div>
      </div>
    </div>,
    document.body
  )
}
