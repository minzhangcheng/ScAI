class DetailedReportGenerator(AnalysisLogMixin, FiguresMixin, ScoringMixin, LLMCallsMixin, PIReviewMixin, PlanningMixin, SectionsMixin):
    """
    Generates detailed research reports based on analysis results.

    Key Design: Agent-Driven Code Generation
    - PI Agent dynamically plans report structure based on analysis findings
    - Bioinformatics Agent autonomously generates code for each figure/table
    - No pre-defined analysis templates - everything is generated on-the-fly
    """

    def __init__(
        self,
        llm_client: OpenAICompatibleClient,
        pi_model: str,
        bio_model: str,
        output_dir: str,
        workspace_dir: str = None,
        progress_callback: Optional[Callable] = None,
        session_id: str = "report",
        vision_settings: Optional[Dict[str, bool]] = None,
        supervisor_model: Optional[str] = None,
        target_lineage_id: str = "main",
        context_budget_callback: Optional[Callable] = None,
        context_budget_ack_callback: Optional[Callable] = None,
    ):
        self._session_id = session_id
        self.llm_client = llm_client
        self.pi_model = pi_model
        self.bio_model = bio_model
        self._output_root = Path(output_dir)
        self._output_root.mkdir(parents=True, exist_ok=True)
        self.output_dir = self._output_root
        self.workspace_dir = Path(workspace_dir) if workspace_dir else None
        self.progress_callback = progress_callback
        self.vision_settings = vision_settings or {}
        self.supervisor_model = supervisor_model or ""
        self.target_lineage_id = target_lineage_id or "main"
        self.context_budget_callback = context_budget_callback
        self.context_budget_ack_callback = context_budget_ack_callback

        # Create subdirectories
        self.figures_dir = self.output_dir / "figures"
        self.tables_dir = self.output_dir / "tables"

        # Track generated outputs
        self.generated_figures: List[Dict[str, Any]] = []
        self.generated_tables: List[Dict[str, Any]] = []
        self.code_history: List[CodeExecution] = []
        self.cluster_annotations: Dict[str, Dict[str, Any]] = {}  # cluster_id -> {cell_type, n_cells}

        # Figure images cache for vision API (populated by _prepare_figure_images)
        self.figure_images_cache: Dict[str, str] = {}  # filename -> raw base64

    async def _report_progress(self, progress: float, step: str, status: str = "generating"):
        """Report progress to callback"""
        if self.progress_callback:
            await self.progress_callback({
                "progress": progress,
                "step": step,
                "status": status
            })

    def _set_llm_context(self, agent_name: str = "report_generator"):
        """Set LLM client context for logging (ReportGenerator doesn't inherit BaseAgent)."""
        self.llm_client.set_context(
            getattr(self, '_session_id', 'report'),
            agent_name
        )

    def _maybe_generate_reproducibility_bundle(
        self,
        state: AnalysisState,
        notebook_src: Path,
    ) -> Optional[str]:
        """Generate reproducibility bundle if enabled, otherwise return None."""
        if not default_config.enable_reproducibility:
            logger.debug("Reproducibility bundle generation skipped (enable_reproducibility=False)")
            return None
        from backend.services.reproducibility import ReproducibilityBundle
        try:
            bundle = ReproducibilityBundle()
            workspace_dir = str(get_session_workspace(state.id))
            notebook_path = str(notebook_src)
            upload_paths = []
            for f in state.data_files:
                if f.file_path and Path(f.file_path).is_file():
                    upload_paths.append(f.file_path)
            bundle_path = bundle.generate(
                session_id=state.id,
                workspace_path=workspace_dir,
                ipynb_path=notebook_path,
                round_results=state.round_results,
                upload_paths=upload_paths,
            )
            logger.info(f"Reproducibility bundle generated at {bundle_path}")
            return bundle_path
        except Exception as e:
            logger.warning(
                f"Failed to generate reproducibility bundle: {e}", exc_info=True
            )
            return None

    async def generate_report(
        self,
        state: AnalysisState,
        resume_from_checkpoint: bool = True,
        force_fallback: bool = False,
    ) -> Dict[str, Any]:
        """Generate and publish a report, optionally without any LLM calls."""
        output_root = self._output_root
        transaction = ReportGenerationTransaction(output_root)
        self.output_dir = transaction.staging_dir
        self.figures_dir = self.output_dir / "figures"
        self.tables_dir = self.output_dir / "tables"
        reset_report_asset_directories(self.output_dir)
        try:
            staged_kwargs = {
                "resume_from_checkpoint": (
                    resume_from_checkpoint and not force_fallback
                )
            }
            if force_fallback:
                staged_kwargs["force_fallback"] = True
            report = await self._generate_report_staged(
                state,
                **staged_kwargs,
            )
            published_dir = await run_in_owned_thread(
                transaction.commit_report,
                report,
            )
            self.output_dir = published_dir
            self.figures_dir = published_dir / "figures"
            self.tables_dir = published_dir / "tables"
            try:
                CheckpointManager(
                    session_id=state.id,
                    state_dir=str(get_session_states(state.id)),
                    prefix="report",
                ).clear()
            except OSError:
                logger.warning(
                    "Published report but could not clear its checkpoint",
                    exc_info=True,
                )
            return report
        except BaseException:
            try:
                await run_in_owned_thread(transaction.abort)
            finally:
                self.output_dir = output_root
                self.figures_dir = output_root / "figures"
                self.tables_dir = output_root / "tables"
            raise

    async def _generate_report_staged(
        self,
        state: AnalysisState,
        resume_from_checkpoint: bool = True,
        force_fallback: bool = False,
    ) -> Dict[str, Any]:
        """
        Generate a detailed research report by compiling existing analysis results.

        Supports checkpoint-based resumption: if a previous attempt was interrupted
        (e.g. API rate limit), the method resumes from the last successfully
        completed step instead of starting over.

        NO code execution or Jupyter sandbox — the report is built entirely from:
        - state.code_history (what analyses were done)
        - state.round_results (what was found)
        - state.publication_figures (PI-reviewed figures)
        - Workspace files (figures and tables generated during analysis)

        Args:
            state: Analysis state with results
            resume_from_checkpoint: Whether to attempt resuming from a saved checkpoint

        Returns:
            Detailed report structure
        """
        return await _staged_owner.generate_report_staged(
            self,
            state,
            resume_from_checkpoint=resume_from_checkpoint,
            force_fallback=force_fallback,
            bindings=sys.modules[__name__],
        )

    async def _generate_html_report(
        self,
        report: Dict[str, Any],
        language: str,
        state: Optional[AnalysisState] = None
    ) -> Path:
        """
        Generate HTML report with embedded images and download links.
        Images are embedded as base64 for standalone HTML display.
        """
        return await _html_owner.generate_html_report(
            self,
            report,
            language,
            state=state,
            bindings=sys.modules[__name__],
        )
