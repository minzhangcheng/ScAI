    async def _generate_html_report(
        self,
        report: Dict[str, Any],
        language: str
    ) -> Path:
        """
        Generate HTML report with embedded images and download links
        """
        zh = language == "zh"

        # Prepare table of contents
        toc_items = []
        for section in report.get("sections", []):
            analysis_type = section.get("analysis_type", "general")
            type_class = "general" if analysis_type == "general" else "specific"
            type_label = ("通用分析" if zh else "General") if analysis_type == "general" else ("特定分析" if zh else "Specific")

            toc_items.append(
                f'<li><a href="#{section["id"]}">{section["title"]}</a>'
                f'<span class="section-type {type_class}">{type_label}</span></li>'
            )

        # Generate sections HTML
        sections_html = []
        for section in report.get("sections", []):
            analysis_type = section.get("analysis_type", "general")
            type_class = "general" if analysis_type == "general" else "specific"
            type_label = ("通用分析" if zh else "General") if analysis_type == "general" else ("特定分析" if zh else "Specific")

            section_html = f'''
            <div class="section" id="{section["id"]}">
                <div class="section-header">
                    <h2>
                        {section["title"]}
                        <span class="analysis-type-badge {type_class}">{type_label}</span>
                    </h2>
                </div>
                <div class="section-content">
                    <p>{section.get("content", "").replace(chr(10), "</p><p>")}</p>
            '''

            # Add figures
            for figure in section.get("figures", []):
                fig_id = figure.get("id", "")
                fig_name = figure.get("name", "Figure")
                png_path = figure.get("png_path", "")
                pdf_path = figure.get("pdf_path", "")

                # Encode PNG image as base64 for embedding
                png_base64 = ""
                if png_path and os.path.exists(png_path):
                    try:
                        with open(png_path, "rb") as f:
                            png_base64 = base64.b64encode(f.read()).decode()
                    except:
                        pass

                # Create relative paths for downloads
                png_filename = os.path.basename(png_path) if png_path else ""
                pdf_filename = os.path.basename(pdf_path) if pdf_path else ""

                section_html += f'''
                    <div class="figure-container">
                        <div class="figure-image">
                            {"<img src='data:image/png;base64," + png_base64 + "' alt='" + fig_name + "' />" if png_base64 else "<p>Image not available</p>"}
                        </div>
                        <div class="figure-caption">
                            <h4>{fig_name}</h4>
                            <div class="figure-actions">
                                <a href="figures/{png_filename}" download class="download-btn png">
                                    {"下载 PNG" if zh else "Download PNG"}
                                </a>
                                {"<a href='figures/" + pdf_filename + "' download class='download-btn pdf'>" + ("下载 PDF (高清)" if zh else "Download PDF (High-Res)") + "</a>" if pdf_path and os.path.exists(pdf_path) else ""}
                            </div>
                        </div>
                    </div>
                '''

            # Add tables
            for table in section.get("tables", []):
                tbl_name = table.get("name", "Table")
                csv_path = table.get("csv_path", "")
                columns = table.get("columns", [])
                preview_data = table.get("preview_data", [])

                csv_filename = os.path.basename(csv_path) if csv_path else ""

                # Build table HTML
                table_header = "".join([f"<th>{col}</th>" for col in columns])
                table_rows = ""
                for row in preview_data[:10]:
                    row_cells = "".join([f"<td>{row.get(col, '-')}</td>" for col in columns])
                    table_rows += f"<tr>{row_cells}</tr>"

                section_html += f'''
                    <div class="table-container">
                        <div class="table-header">
                            <h4>{tbl_name}</h4>
                            <a href="tables/{csv_filename}" download class="download-btn csv">
                                {"下载 CSV" if zh else "Download CSV"}
                            </a>
                        </div>
                        <div class="table-wrapper">
                            <table>
                                <thead><tr>{table_header}</tr></thead>
                                <tbody>{table_rows}</tbody>
                            </table>
                        </div>
                        {"<div class='table-info'>" + (f"显示前10行，共{len(preview_data)}行" if zh else f"Showing 10 of {len(preview_data)} rows") + "</div>" if len(preview_data) > 10 else ""}
                    </div>
                '''

            section_html += '''
                </div>
            </div>
            '''
            sections_html.append(section_html)

        # Build full HTML
        html_content = HTML_TEMPLATE.format(
            language="zh" if zh else "en",
            title=report.get("title", "Analysis Report"),
            generated_at=("生成时间: " if zh else "Generated: ") + report.get("generated_at", ""),
            toc_title="目录" if zh else "Table of Contents",
            toc_items="\n".join(toc_items),
            abstract_title="摘要" if zh else "Abstract",
            abstract=report.get("abstract", "").replace("\n", "<br>"),
            sections_html="\n".join(sections_html),
            conclusions_title="结论" if zh else "Conclusions",
            conclusions=report.get("conclusions", "").replace("\n", "<br>")
        )

        # Save HTML file
        html_path = self.output_dir / "report.html"
        with open(html_path, "w", encoding="utf-8") as f:
            f.write(html_content)

        logger.info(f"HTML report saved to: {html_path}")

        return html_path
