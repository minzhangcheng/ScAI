def _safe_parse_json(response: str) -> Optional[dict]:
    """Parse JSON from LLM response using balanced bracket matching (avoids greedy regex)."""
    if not response:
        return None
    start = response.find('{')
    if start == -1:
        return None
    depth = 0
    in_string = False
    escape_next = False
    end = start
    for i, c in enumerate(response[start:], start):
        if escape_next:
            escape_next = False
            continue
        if c == '\\' and in_string:
            escape_next = True
            continue
        if c == '"':
            in_string = not in_string
            continue
        if in_string:
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    if depth == 0 and end > start:
        try:
            return json.loads(response[start:end])
        except json.JSONDecodeError:
            logger.debug("JSON extraction from LLM response failed at position %d-%d", start, end)
    return None


def markdown_to_html(text: str) -> str:
    """Convert basic markdown formatting to HTML"""
    if not text:
        return ""

    # Escape HTML entities first to prevent XSS
    text = html_module.escape(text)

    # Headers: must be processed before bold/italic (longest prefix first)
    text = re.sub(r'^####\s+(.+)$', r'<h4>\1</h4>', text, flags=re.MULTILINE)
    text = re.sub(r'^###\s+(.+)$', r'<h3>\1</h3>', text, flags=re.MULTILINE)
    text = re.sub(r'^##\s+(.+)$', r'<h2>\1</h2>', text, flags=re.MULTILINE)
    text = re.sub(r'^#\s+(.+)$', r'<h1>\1</h1>', text, flags=re.MULTILINE)

    # Bold: **text** or __text__
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    text = re.sub(r'__(.+?)__', r'<strong>\1</strong>', text)

    # Italic: *text* or _text_
    text = re.sub(r'\*(.+?)\*', r'<em>\1</em>', text)
    text = re.sub(r'_(.+?)_', r'<em>\1</em>', text)

    # Code: `text`
    text = re.sub(r'`(.+?)`', r'<code>\1</code>', text)

    # Bullet lists
    text = re.sub(r'^- (.+)$', r'<li>\1</li>', text, flags=re.MULTILINE)
    text = re.sub(r'(<li>.*?</li>\n?)+', r'<ul>\g<0></ul>', text)

    # Markdown tables — process BEFORE line-break substitution
    def _convert_table_block(m):
        lines = m.group(0).strip().split('\n')
        html = '<div class="table-wrapper"><table>'
        in_body = False
        for line in lines:
            line = line.strip()
            if not line or not line.startswith('|'):
                continue
            cells = [c.strip() for c in line.strip('|').split('|')]
            # Separator row (e.g. |---|---|)
            if all(re.match(r'^[-: ]+$', c) for c in cells if c.strip()):
                if not in_body:
                    html += '</thead><tbody>'
                    in_body = True
                continue
            if not in_body:
                html += '<thead><tr>' + ''.join(f'<th>{c}</th>' for c in cells) + '</tr>'
            else:
                html += '<tr>' + ''.join(f'<td>{c}</td>' for c in cells) + '</tr>'
        if not in_body:
            html += '</thead><tbody>'
        html += '</tbody></table></div>'
        return html

    text = re.sub(r'(?:^[ \t]*\|[^\n]*\n?)+', _convert_table_block, text, flags=re.MULTILINE)

    # Line breaks
    text = text.replace('\n\n', '</p><p>')
    text = text.replace('\n', '<br>')

    return text


