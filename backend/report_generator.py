def save_figure(fig, base_path, dpi_png=150, dpi_pdf=300):
    '''Save figure as both PNG (for display) and PDF (for editing)'''
    base_path = Path(base_path)
    png_path = base_path.with_suffix('.png')
    pdf_path = base_path.with_suffix('.pdf')

    # Save PNG for web display
    fig.savefig(png_path, dpi=dpi_png, bbox_inches='tight', facecolor='white')

    # Save PDF for high-quality editing
    fig.savefig(pdf_path, dpi=dpi_pdf, bbox_inches='tight', format='pdf')

    print(f"Saved: {png_path} and {pdf_path}")
    return str(png_path), str(pdf_path)

