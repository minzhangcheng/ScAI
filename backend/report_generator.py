                return {
                    "id": section_id,
                    "title": section_title,
                    "description": section_description,
                    "analysis_type": analysis_type,
                    "content": narrative,
                    "figures": section_figures,
                    "tables": section_tables,
                    "pi_iterations": 1,
                    "steps_executed": 1
                }

