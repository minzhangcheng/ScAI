"""Domain-neutral evidence policy for biological mechanism discovery."""

MECHANISM_EVIDENCE_POLICY = (
    "Begin with unbiased analyses and do not assume or privilege a named mechanism "
    "without supporting evidence. When observed genes, pathways, enrichment results, "
    "measurements, morphology, or perturbation responses match an established biological "
    "mechanism, name it explicitly and grade the supporting and contradictory evidence. "
    "Treat mechanisms explicitly named in the research objective or current direction as "
    "prespecified hypotheses: evaluate each as supported, contradicted, or insufficiently "
    "supported without treating it as established by default. Distinguish pathway activity, "
    "susceptibility, or priming from causal mechanism execution."
)
