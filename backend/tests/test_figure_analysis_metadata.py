"""Figure methods survive registration and reach report writers without inference."""
from unittest.mock import AsyncMock

import pytest

from backend.agents.pi.reports import ReportsMixin
from backend.agents.supervisor_agent import SupervisorAgent
from backend.models.schemas import AnalysisState, IntegratedReportFigureRef
from backend.routes.chat_parts.delegation import _build_execution_context
from backend.services.report.figure_discovery import publication_figure_metadata
from backend.services.report.generator import DetailedReportGenerator
from backend.services.report.round_chapters import chapter_prompt, round_artifact_catalog
from backend.tests.test_figure_revision_gate import (
    CLEAN, _Agent, _FakeSandbox, _review, _reviews,
)
from backend.tests.test_round_report_chapters import _state


METHODS = {
    "data_source": "results/contrast_A.csv; generated by execution model-fit-A",
    "sample_design": "Three independent samples per group; pairing unknown.",
    "methods": "Panel A: condition-only model (~condition); contrast B vs A.",
    "parameters": "BH adjustment; score definition score-A; seed 42.",
    "limitations": "Panel B is descriptive; historical input scale is unconfirmed.",
}


@pytest.mark.asyncio
async def test_registration_persists_methods_through_visual_revision(tmp_path):
    agent = _Agent(_FakeSandbox(tmp_path, [CLEAN, CLEAN]))
    state = AnalysisState(user_id="u")
    await agent._handle_generate_publication_figure(
        code="plot()", figure_name="f", description="Contrast", figure_type="heatmap",
        state=state, analysis_metadata=METHODS,
        review_callback=_reviews(_review(), _review(approved=True, score=9)),
    )
    assert len(agent.revision_calls) == 1
    loaded = AnalysisState.model_validate_json(state.model_dump_json())
    figure = loaded.publication_figures[0]
    assert figure.analysis_metadata == METHODS
    assert figure.review_status.value == "approved"
    assert publication_figure_metadata(loaded.publication_figures)["f"]["analysis_metadata"] == METHODS
    context = _build_execution_context({"figure_review_records": [figure.model_dump(mode="json")]})
    assert METHODS["methods"] in context


@pytest.mark.parametrize("registered", [False, True])
def test_round_and_detailed_report_context_preserve_methods_and_legacy_fallback(tmp_path, registered):
    state = _state(tmp_path)
    figure = state.publication_figures[0]
    if registered:
        figure.analysis_metadata = METHODS
    else:
        # Persisted records from older versions have no such field.
        old = state.model_dump(mode="json")
        for item in old["publication_figures"]:
            item.pop("analysis_metadata", None)
        state = AnalysisState.model_validate(old)
    catalog = round_artifact_catalog(state)
    assert len(catalog) == 2
    chapter = chapter_prompt(catalog, state=state)
    agent = SupervisorAgent.__new__(SupervisorAgent)
    figure_map = {"late_result.jpg": tmp_path / "late_result.jpg", "legacy.png": tmp_path / "legacy.png"}
    prompt = agent._build_report_prompt("Recorded execution", {}, state, figure_map, "en")
    for value in METHODS.values():
        assert (value in chapter) is registered
        assert (value in prompt) is registered
    assert "legacy.png" in prompt


@pytest.mark.asyncio
async def test_integrated_report_uses_frozen_methods_not_later_live_changes(tmp_path):
    state = _state(tmp_path)
    figure = state.publication_figures[0]
    ref = IntegratedReportFigureRef(
        number=1, figure_id=figure.id, name=figure.name,
        analysis_metadata=METHODS,
    )
    ref = IntegratedReportFigureRef.model_validate_json(ref.model_dump_json())
    figure.analysis_metadata = {"methods": "A later and different model"}
    pi = ReportsMixin()
    pi.session_id = "test"
    pi.chat = AsyncMock(return_value="Report")
    await pi.generate_integrated_report(state, figure_refs=[ref])
    prompt = pi.chat.call_args.args[0]
    for value in METHODS.values():
        assert value in prompt
    assert "A later and different model" not in prompt


@pytest.mark.asyncio
async def test_alternate_report_receives_methods_even_without_vision(tmp_path):
    state = _state(tmp_path)
    state.publication_figures[0].analysis_metadata = METHODS
    writer = DetailedReportGenerator.__new__(DetailedReportGenerator)
    writer._pi_chat = AsyncMock(return_value='{"analysis_workflow": "Recorded methods"}')
    await writer._pi_comprehensive_review("Code digest", {}, {}, state, "en")
    writer._pi_chat.assert_awaited_once()
    prompt = writer._pi_chat.call_args.args[0]
    for value in METHODS.values():
        assert value in prompt
