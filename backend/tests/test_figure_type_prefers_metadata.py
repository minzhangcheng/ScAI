"""P2-10: Figure type inference must prefer agent-declared figure_type metadata
over filename heuristics.

Regression test for docs/problems.md P2-10. The legacy implementation inferred
figure types purely from filename keywords (umap, leiden, dpt, ...). Figures
generated by tools that don't follow scanpy naming conventions (matplotlib
directly, R via reticulate) cannot be classified that way. When the agent
declares `figure_type` via the `generate_publication_figure` tool, that value
must be honored authoritatively.
"""

from backend.services.report.figures import FiguresMixin


def test_metadata_overrides_filename_heuristic():
    """Declared figure_type must win even when filename suggests another type."""
    # Filename screams "umap" but agent declared this is a volcano plot.
    result = FiguresMixin._infer_figure_type(
        "umap_clusters", declared_type="volcano"
    )
    assert result == "volcano", (
        f"P2-10: metadata figure_type must override filename heuristic, got {result!r}"
    )


def test_metadata_overrides_with_arbitrary_custom_type():
    """Non-standard agent-declared types (e.g. from R plots) must pass through."""
    result = FiguresMixin._infer_figure_type(
        "plot_001", declared_type="ridge_plot"
    )
    assert result == "ridge_plot", (
        f"P2-10: arbitrary declared type must be honored, got {result!r}"
    )


def test_fallback_to_filename_when_no_metadata():
    """Filename heuristic still applies when no figure_type is declared."""
    assert FiguresMixin._infer_figure_type("umap_clusters") == "umap"
    assert FiguresMixin._infer_figure_type("leiden_clustering") == "clustering"
    assert FiguresMixin._infer_figure_type("dpt_pseudotime") == "trajectory"


def test_empty_declared_type_falls_back_to_filename():
    """Empty/None declared_type must not break heuristic fallback."""
    assert FiguresMixin._infer_figure_type("umap_clusters", declared_type=None) == "umap"
    assert FiguresMixin._infer_figure_type("umap_clusters", declared_type="") == "umap"
