#!/bin/bash
set -euo pipefail

if [ "$#" -ne 2 ]; then
    echo "Usage: link_frontend_node_modules.sh FRONTEND_DIR NODE_MODULES_DIR" >&2
    exit 2
fi

FRONTEND_DIR=$(cd "$1" && pwd -P)
NODE_MODULES_DIR=$(cd "$2" && pwd -P)
LINK_PATH="$FRONTEND_DIR/node_modules"

if [ -L "$LINK_PATH" ]; then
    CURRENT_TARGET=$(readlink -f "$LINK_PATH" || true)
    if [ "$CURRENT_TARGET" != "$NODE_MODULES_DIR" ]; then
        # The target is known to be a symlink; unlinking it cannot remove the
        # legacy dependency directory it points at.
        unlink "$LINK_PATH"
    fi
elif [ -e "$LINK_PATH" ]; then
    echo "Error: $LINK_PATH exists and is not a symlink; move it aside before startup." >&2
    exit 1
fi

if [ ! -L "$LINK_PATH" ]; then
    ln -s "$NODE_MODULES_DIR" "$LINK_PATH"
fi
